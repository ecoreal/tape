// Typographic characters agent transcripts are full of → ASCII we can draw.
const TRANSLIT = {
  '…': '...', '·': '*', '•': '*', '—': '-', '–': '-', '→': '>', '←': '<',
  '✓': '+', '✔': '+', '✗': 'x', '×': 'x', '⏪': '<', '⚔': 'x', '↑': '^',
  '↓': 'v', '“': '"', '”': '"', '‘': "'", '’': "'", '≥': '>', '≤': '<',
  '⏎': '/', '\t': ' ', '│': '|', '─': '-', '▸': '>', '≡': '=',
};

/** Anything the font can draw. Unknown characters are dropped (they are almost
 *  always decoration; a wall of '?' would be worse than a gap). */
export function drawable(s) {
  let out = '';
  const text = String(s);
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const mapped = TRANSLIT[ch] ?? ch;
    for (const c of mapped) {
      const up = c.toUpperCase();
      if (G[up]) out += up;
    }
  }
  return out;
}

/** Rows for one character, or null when the font has no glyph. */
